/** 简单的 {name} 占位替换 */
export function fmt(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
}

/**
 * 中文不分单复数；英文在 n === 1 时要用另一套说法（"1 day left" 而不是 "1 days left"）。
 * zhTpl 只给中文用，enOne / enMany 只给英文用，缺的那一侧不会被访问。
 */
export function p(lang, n, zhTpl, enOne, enMany, vars = {}) {
  if (lang !== 'en') return fmt(zhTpl, { n, ...vars });
  return fmt(n === 1 ? enOne : enMany, { n, ...vars });
}
